CREATE TABLE RoyHadad_School (
    school_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_name VARCHAR2(255),
    settlement VARCHAR2(255),
    area VARCHAR2(255),
    CONSTRAINT chk_area
        CHECK  (area IN ('south' , 'center' , 'north'))
);

CREATE TABLE RoyHadad_Student(
    student_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id NUMBER,
    first_name VARCHAR2(255),
    last_name VARCHAR2(255),

    CONSTRAINT fk_school
        FOREIGN KEY (school_id)
        REFERENCES RoyHadad_School(school_id)
);

CREATE TABLE RoyHadad_Exam(
    exam_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id NUMBER,
    school_id NUMBER,
    score NUMBER,
    field VARCHAR2(255),
    exam_name VARCHAR2(255),
    exam_date DATE,

    CONSTRAINT fk_exam_student
        FOREIGN KEY (student_id)
        REFERENCES RoyHadad_Student(student_id)
        ,
    CONSTRAINT fk_exam_school
        FOREIGN KEY (school_id)
        REFERENCES RoyHadad_School(school_id)
        ,
    CONSTRAINT chk_score
        CHECK (score BETWEEN 0 AND 100)
);

