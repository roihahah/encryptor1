SELECT school_id ,  school_name , student_id , first_name , last_name , avg_score
FROM (
    SELECT sc.school_id , sc.school_name , s.student_id , s.first_name , s.last_name , AVG(e.score) AS avg_score , RANK()
        OVER(PARTITION BY sc.school_id  ORDER BY AVG(e.score) DESC
    ) AS rnk
    FROM RoyHadad_School sc
    JOIN RoyHadad_Student s
    ON s.school_id = sc.school_id
    JOIN RoyHadad_Exam e
    ON s.student_id = e.student_id AND e.school_id = sc.school_id
    GROUP BY sc.school_id , sc.school_name , s.student_id ,  s.first_name , s.last_name
)
WHERE rnk = 1
ORDER BY avg_score DESC;

